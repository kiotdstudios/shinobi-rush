import {chromium} from '../../../scripts/ci/smoke/node_modules/playwright/index.mjs';
import {startStaticServer} from '../../../scripts/ci/smoke/lib/serve.mjs';
import {mkdirSync,writeFileSync} from 'node:fs';
const arg=n=>{const i=process.argv.indexOf('--'+n);return i<0?undefined:process.argv[i+1]};
const out=arg('out-dir')||'docs/visuals/purple-lilies/gameplay';mkdirSync(out,{recursive:true});
const server=arg('serve-dir')?await startStaticServer(arg('serve-dir')):null;
const base=arg('url')||server.url;
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:720},serviceWorkers:'block'});
const page=await context.newPage(),checks=[],errors=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error'||/SCRIPT ERROR|^ERROR:/.test(m.text()))errors.push(m.text())});
const ck=(name,ok,detail)=>{checks.push({name,ok,detail});console.log(`${ok?'PASS':'FAIL'} ${name}`);if(!ok)throw Error(name)};
const cliff=()=>page.evaluate(()=>({...window.__CLIFF_REVIEW__}));
const play=()=>page.evaluate(()=>({...window.__WATERLIFE_PLAY__}));
const pads=s=>JSON.parse(s.pads_json);
try{
 if(arg('expected-sha')){const b=await(await fetch(base+'build-info.json?v='+Date.now())).json();ck('exact deployed runtime',b.commit_sha===arg('expected-sha'),b)}
 await page.goto(base+'?cliffs=river&map_editor=1&foliage=1');
 await page.waitForFunction(()=>window.__CLIFF_REVIEW__?.ready,null,{timeout:180000});
 let s=await cliff(),plants=JSON.parse(s.foliage_json);
 ck('all ferns are purple while vines keep original colors',plants.filter(p=>p.id.startsWith('blight_fern')).every(p=>p.tint==='d27dffff')&&plants.filter(p=>p.id.startsWith('blight_vine')).every(p=>p.tint==='ffffffff'),plants);
 const cards=JSON.parse(s.cards_json),card=cards.blight_fern_03;
 ck('all six foliage cards remain available',Object.entries(cards).filter(([id,c])=>id.startsWith('blight_')&&c.visible).length===6);
 await page.mouse.click(card.x,card.y);await page.waitForFunction(()=>window.__CLIFF_REVIEW__.place_id==='blight_fern_03');
 s=await cliff();await page.mouse.move(s.paint_x,s.paint_y);await page.waitForTimeout(100);
 await page.screenshot({path:out+'/purple-ghost.png'});
 await page.mouse.click(s.paint_x,s.paint_y);
 await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===16);
 ck('newly placed fern also uses purple variant',JSON.parse((await cliff()).foliage_json).filter(p=>p.id.startsWith('blight_fern')).every(p=>p.tint==='d27dffff'));
 await page.screenshot({path:out+'/editor.png'});
 await page.goto(base+'?waterlife=play');
 await page.waitForFunction(()=>window.__WATERLIFE_PLAY__?.ready,null,{timeout:120000});
 const start=await play(),anchors=pads(start).slice(0,6).map(p=>[p.x,p.y]);
 ck('real player starts dry with unchanged pool',!start.wet&&!start.aura&&start.pool===32&&anchors.length===6,start);
 await page.keyboard.down('KeyD');
 await page.waitForFunction(()=>window.__WATERLIFE_PLAY__.x>=655,null,{timeout:20000});
 await page.keyboard.up('KeyD');
 let wet=await play(),touched=pads(wet).filter(p=>p.touches>0);
 ck('real water-running reaches and disturbs multiple plants',wet.wet&&wet.aura&&touched.length>=3&&wet.emissions>=2&&touched.some(p=>p.push>0.1),wet);
 ck('touched plants have varied recovery speeds',new Set(touched.map(p=>p.rate.toFixed(2))).size>=3&&touched.every(p=>p.rate>=2.6&&p.rate<=5.4),touched);
 ck('contact dips down and preserves water depth',touched.every(p=>p.dip>=0&&p.depth===0&&p.push<5),touched);
 ck('normal chakra cost is still applied',wet.chakra<start.chakra&&wet.chakra>0,{start:start.chakra,wet:wet.chakra});
 await page.screenshot({path:out+'/contact.png'});
 await page.waitForFunction(()=>JSON.parse(window.__WATERLIFE_PLAY__.pads_json).filter(p=>p.touches>0).every(p=>p.push===0),null,{timeout:12000});
 const settled=await play();
 ck('plants fully settle while player remains on water',settled.wet&&settled.chakra>0&&pads(settled).filter(p=>p.touches>0).every(p=>Math.abs(p.draw_y-p.y)<=1),settled);
 await page.screenshot({path:out+'/settled.png'});
 const emissions=settled.emissions;
 await page.waitForFunction(t=>window.__WATERLIFE_PLAY__.clock>t+.3,settled.clock);
 ck('standing creates no repeated running spray',(await play()).emissions===emissions);
 await page.keyboard.down('KeyA');await page.waitForFunction(()=>window.__WATERLIFE_PLAY__.x<=480,null,{timeout:12000});await page.keyboard.up('KeyA');
 ck('second crossing reuses bounded reactions',pads(await play()).some(p=>p.touches>=2)&&pads(await play()).every(p=>p.push<5));
 await page.keyboard.down('KeyW');await page.waitForFunction(()=>!window.__WATERLIFE_PLAY__.wet,null,{timeout:12000});await page.keyboard.up('KeyW');
 await page.waitForFunction(()=>JSON.parse(window.__WATERLIFE_PLAY__.pads_json).every(p=>p.push===0),null,{timeout:12000});
 const dry=await play();
 ck('recovery also completes after leaving water',!dry.wet&&!dry.aura&&dry.chakra>0&&pads(dry).every(p=>Math.abs(p.draw_y-p.y)<=1),dry);
 ck('original plant anchors never drift',pads(dry).slice(0,6).every((p,i)=>p.x===anchors[i][0]&&p.y===anchors[i][1]));
 ck('one eligible visit remains one frog rarity roll',dry.rolls===1&&dry.pool===32,{rolls:dry.rolls,pool:dry.pool});
 await page.screenshot({path:out+'/dry-recovery.png'});
 ck('zero browser or engine errors',errors.length===0,errors);
}catch(e){checks.push({name:'completed',ok:false,detail:String(e)});console.log('FAIL',String(e));await page.screenshot({path:out+'/failure.png'});}
finally{await context.close();await browser.close();if(server)await server.close();writeFileSync(out+'/result.json',JSON.stringify({utc:new Date().toISOString(),checks,errors},null,2));}
process.exit(checks.every(c=>c.ok)?0:1);
