import {chromium} from 'playwright';
import {mkdirSync,writeFileSync} from 'node:fs';
import {startStaticServer} from './lib/serve.mjs';
const arg=n=>{const i=process.argv.indexOf('--'+n);return i<0?undefined:process.argv[i+1]};
const out=arg('out-dir')||'docs/visuals/vines-ferns/gameplay';mkdirSync(out,{recursive:true});
const server=arg('serve-dir')?await startStaticServer(arg('serve-dir')):null;
const base=arg('url')||server.url;
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:720},serviceWorkers:'block'});
const page=await context.newPage(),checks=[],errors=[];
const monitor=p=>{p.on('pageerror',e=>errors.push(String(e)));p.on('console',m=>{if(m.type()==='error'||/SCRIPT ERROR|^ERROR:/.test(m.text()))errors.push(m.text())})};
monitor(page);
const check=(name,ok,detail)=>{checks.push({name,ok,detail});console.log(`${ok?'PASS':'FAIL'} ${name}`);if(!ok)throw Error(name)};
const state=()=>page.evaluate(()=>({...window.__CLIFF_REVIEW__}));
const plants=s=>JSON.parse(s.foliage_json);
const click=async index=>{const p=JSON.parse((await state()).buttons_json)[index];await page.mouse.click(p.x,p.y);await page.waitForTimeout(150)};
try{
 if(arg('expected-sha')){const b=await(await fetch(new URL('build-info.json?v='+Date.now(),base))).json();check('exact deployed runtime',b.commit_sha===arg('expected-sha'),b)}
 await page.goto(base+'?cliffs=river&editor=1&foliage=1');
 await page.waitForFunction(()=>window.__CLIFF_REVIEW__?.ready,null,{timeout:180000});
 let s=await state();const before=plants(s);
 check('dressed map contains six distinct assets and fifteen plants',before.length===15&&new Set(before.map(p=>p.id)).size===6&&s.cells===134,s);
 await page.waitForTimeout(850);const after=plants(await state());
 check('anchored sway advances without root movement',after.some((p,i)=>p.phase!==before[i].phase)&&after.every((p,i)=>p.x===before[i].x&&p.y===before[i].y),{before,after});
 await page.screenshot({path:out+'/overview.png'});
 await click(6);await page.screenshot({path:out+'/cliff-detail.png'});
 await page.goto(base+'?cliffs=river&map_editor=1&foliage=1');
 await page.waitForFunction(()=>window.__CLIFF_REVIEW__?.ready,null,{timeout:180000});
 const original=await page.evaluate(()=>localStorage.getItem('shinobi-rush:world-layout:v1'));
 s=await state();const cards=Object.entries(JSON.parse(s.cards_json)).filter(([id])=>id.startsWith('blight_'));
 check('actual editor opens six foliage cards',s.editor_open&&cards.length===6&&cards.every(([,c])=>c.visible),cards);
 await page.mouse.click(s.foliage_layer_x,s.foliage_layer_y);
 await page.waitForFunction(()=>window.__CLIFF_REVIEW__.foliage_visible===false);
 check('layer eye hides every foliage sprite while retaining cliffs',plants(await state()).every(p=>!p.visible)&&(await state()).cliffs_visible,await state());
 await page.mouse.click(s.foliage_layer_x,s.foliage_layer_y);
 await page.waitForFunction(()=>window.__CLIFF_REVIEW__.foliage_visible===true);
 check('layer eye restores foliage',plants(await state()).every(p=>p.visible));
 const card=JSON.parse((await state()).cards_json).blight_fern_01;
 await page.mouse.click(card.x,card.y);await page.waitForFunction(()=>window.__CLIFF_REVIEW__.place_id==='blight_fern_01');
 s=await state();await page.mouse.click(s.paint_x,s.paint_y);
 await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===16);
 check('real card places a separate fern',true,await state());
 await page.keyboard.press('Control+KeyZ');await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===15);
 await page.keyboard.press('Control+KeyY');await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===16);
 check('actual undo and redo preserve placed fern',true);
 s=await state();const target=plants(s).find(p=>p.id==='blight_fern_01');const tool=JSON.parse(s.tools_json).select;
 await page.mouse.click(tool.x,tool.y);await page.mouse.move(target.pick_x,target.pick_y);await page.mouse.down();
 await page.mouse.move(target.pick_x+60,target.pick_y,{steps:10});await page.mouse.up();
 await page.waitForFunction(x=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).some(p=>p.id==='blight_fern_01'&&p.y>=150&&p.y<=210&&Math.abs(p.x-x)>20),target.x);
 check('real leaf picking and drag moves the fern',(await state()).selected_id==='blight_fern_01',await state());
 await page.keyboard.press('Control+KeyZ');
 await page.waitForFunction(t=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).some(p=>p.id===t.id&&p.x===t.x&&p.y===t.y),target);
 s=await state();const erase=JSON.parse(s.tools_json).erase;await page.mouse.click(erase.x,erase.y);await page.mouse.click(target.pick_x,target.pick_y);
 await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===15);
 await page.keyboard.press('Control+KeyZ');await page.waitForFunction(()=>JSON.parse(window.__CLIFF_REVIEW__.foliage_json).length===16);
 check('real erase and undo restores the decoration',true);
 await click(4);await page.waitForFunction(()=>window.__CLIFF_REVIEW__.operations===1);
 check('actual file save reload preserves all edited foliage',plants(await state()).length===16,await state());
 await page.screenshot({path:out+'/editor.png'});
 s=await state();const event=context.waitForEvent('page');await page.mouse.click(s.play_x,s.play_y);const popup=await event;monitor(popup);
 await popup.waitForFunction(()=>window.__CLIFF_REVIEW__?.ready,null,{timeout:180000});
 const played=await popup.evaluate(()=>({...window.__CLIFF_REVIEW__}));
 check('Playtest loads edited foliage in actual game',plants(played).length===16&&played.cells===134,played);
 check('normal saved world remains unchanged',await page.evaluate(original=>localStorage.getItem('shinobi-rush:world-layout:v1')===original,original));
 await popup.close();check('zero browser or engine errors',errors.length===0,errors);
}catch(e){checks.push({name:'completed',ok:false,detail:String(e)});console.log('FAIL',String(e));await page.screenshot({path:out+'/failure.png'});checks.push({name:'failure state',ok:false,detail:await state()});}
finally{await context.close();await browser.close();if(server)await server.close();writeFileSync(out+'/result.json',JSON.stringify({utc:new Date().toISOString(),checks,errors},null,2));}
process.exit(checks.every(c=>c.ok)?0:1);
