def main_gd(variant: str) -> str:
    if variant == "parse_error_referenced":
        # The main scene's own script is broken (missing indentation): Godot's import prints SCRIPT ERROR but exits 0.
        return _gd(["extends Control", "", "func _ready() -> void:", 'print("SELFTEST_READY")'])
    if variant == "blank_canvas":
        # No visible nodes: the canvas shows only the default clear colour (uniform).
        return _gd(
            [
                "extends Control",
                "",
                "func _ready() -> void:",
                '\tprint("SELFTEST_READY (blank canvas variant)")',
                '\tif OS.has_feature("web"):',
                '\t\tJavaScriptBridge.eval("window.__SHINOBI_READY__ = true;")',
            ]
        )
    repo_shaped = variant in REPO_SHAPED
    lines = [
        "extends Control",
        "## PIPELINE SELF-TEST FIXTURE. Generated at runtime by scripts/ci/selftest. NOT THE GAME.",
        "",
        "const MOVE_STEP := 40.0",
        f'const BANNER := "{BANNER}"',
    ]
    if repo_shaped:
        lines.append('const PlayerController := preload("res://scripts/player/player_controller.gd")')
    lines += [
        "",
        'const QUADRANT_COLORS := [Color("1d6fe0"), Color("e0431d"), Color("1de08a"), Color("b21de0")]',
        "const QUADRANT_ORIGINS := [Vector2(0, 0), Vector2(0.5, 0), Vector2(0, 0.5), Vector2(0.5, 0.5)]",
        "",
        "var _square: ColorRect",
        "var _label: Label",
        "var _moves := 0",
        "",
        "func _ready() -> void:",
        "\tfor i in range(4):",
        "\t\tvar quadrant := ColorRect.new()",
        "\t\tquadrant.color = QUADRANT_COLORS[i]",
        "\t\tquadrant.anchor_left = QUADRANT_ORIGINS[i].x",
        "\t\tquadrant.anchor_right = QUADRANT_ORIGINS[i].x + 0.5",
        "\t\tquadrant.anchor_top = QUADRANT_ORIGINS[i].y",
        "\t\tquadrant.anchor_bottom = QUADRANT_ORIGINS[i].y + 0.5",
        "\t\tadd_child(quadrant)",
        "\t_label = Label.new()",
        '\t_label.text = BANNER + "   moves: 0"',
        "\t_label.position = Vector2(16, 16)",
        "\tadd_child(_label)",
        "\t_square = ColorRect.new()",
        '\t_square.color = Color("ffd400")',
        "\t_square.size = Vector2(64, 64)",
        "\t_square.position = Vector2(64, 200)",
        "\tadd_child(_square)",
        '\tprint("SELFTEST_READY")',
    ]
    if repo_shaped:
        lines += [
            "\tvar controller := PlayerController.new()",
            '\tprint("SELFTEST_REPO_SHAPED speed=%s" % controller.speed())',
        ]
    if variant == "startup_error":
        lines.append('\tpush_error("SELFTEST_INTENTIONAL_STARTUP_ERROR")')
    if variant == "startup_script_error":
        lines += [
            "\tvar nothing = null",
            "\tnothing.selftest_nonexistent_method()",
        ]
    if variant == "page_error":
        lines.append('\tif OS.has_feature("web"):')
        lines.append(
            "\t\tJavaScriptBridge.eval(\"setTimeout(function(){ throw new Error('SELFTEST_PAGE_ERROR'); }, 100);\")"
        )
    lines += [
        '\tif OS.has_feature("web"):',
        '\t\tJavaScriptBridge.eval("window.__SHINOBI_READY__ = true;")',
        "",
        "func _unhandled_input(event: InputEvent) -> void:",
        '\tif event.is_action_pressed("ui_right"):',
        "\t\t_moves += 1",
        "\t\t_square.position.x += MOVE_STEP",
        '\t\t_label.text = BANNER + "   moves: %d" % _moves',
    ]
    return _gd(lines)


