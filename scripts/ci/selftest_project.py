def png_bytes(rgb: tuple = (214, 36, 110), size: int = 8) -> bytes:
    """A small valid RGB PNG (solid colour) built with struct/zlib; Godot imports it like any texture."""
    raw = b"".join(b"\x00" + bytes(rgb) * size for _ in range(size))  # filter type 0 per scanline

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def inside_or_above_repo(dest: pathlib.Path) -> bool:
    dest = dest.resolve()
    return dest == REPO_ROOT or REPO_ROOT in dest.parents or dest in REPO_ROOT.parents


def write_project(dest: pathlib.Path, variant: str = "good") -> pathlib.Path:
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant {variant!r}")
    dest = pathlib.Path(dest)
    if inside_or_above_repo(dest):
        raise ValueError(f"refusing to write a generated self-test project inside (or above) the repository: {dest.resolve()}")
    dest = prepare_owned_dir(dest)  # refuses a non-empty directory this tooling did not create

    def wb(rel: str, data: bytes) -> None:
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)

    def w(rel: str, text: str) -> None:
        wb(rel, text.encode("utf-8"))  # bytes => LF, no BOM

    w("project.godot", project_godot(variant))
    w("export_presets.cfg", export_presets(variant))
    w("icon.svg", ICON_SVG)
    w("main.tscn", MAIN_TSCN)
    w("main.gd", main_gd(variant))
    if variant == "parse_error":
        w("broken.gd", BROKEN_GD)
    if variant in REPO_SHAPED:
        w("scripts/player/player_controller.gd", PLAYER_CONTROLLER_GD)
        w("scripts/player/helper.gd", HELPER_GD)
        for folder in NON_GAME_FOLDERS:
            w(f"{folder}/.gdignore", "")
            w(f"{folder}/README.md", f"{folder}: documentation, not a game resource. Generated by the pipeline self-test.\n")
        # The good layout ignores only the CI tooling folder. The negative layout ignores scripts/ as a whole, which hides
        # the game code under scripts/player from the import scan, load()/preload() and the export (rule PRJ013).
        w("scripts/ci/.gdignore" if variant == "repo_shaped" else "scripts/.gdignore", "")
    if variant == "repo_shaped":
        # Non-game folders with IMAGES behind a .gdignore, game art without one, and a control folder that is NOT ignored.
        w(f"{REFERENCES_FOLDER}/.gdignore", "")
        w(f"{REFERENCES_FOLDER}/README.md", "Reference art, not a game resource. Generated by the pipeline self-test.\n")
        wb(GAME_ART, png_bytes((30, 111, 224)))
        wb(CONTROL_IMAGE, png_bytes((224, 67, 29)))
        wb(IGNORED_IMAGES[0], png_bytes((29, 224, 138)))
        wb(IGNORED_IMAGES[1], ICON_SVG.encode("utf-8"))
        wb(IGNORED_IMAGES[2], png_bytes((178, 29, 224)))
        # Invalid scripts that must never be loaded (behind a .gdignore, or in a dot folder) and valid scripts in folders
        # the walker skips by rule: the walker's script count must stay GAME_SCRIPT_COUNT.
        for rel in BROKEN_DECOYS:
            w(rel, BROKEN_GD)
        for rel in VALID_DECOYS:
            w(rel, VALID_DECOY_GD)
    return dest


if __name__ == "__main__":
    out = pathlib.Path(sys.argv[1])
    variant = sys.argv[2] if len(sys.argv) > 2 else "good"
    write_project(out, variant)
    print(f"wrote {variant} project to {out}")
