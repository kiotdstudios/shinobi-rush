def _gd(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def project_godot(variant: str) -> str:
    main_scene = {
        "missing_main_scene": 'run/main_scene="res://does_not_exist.tscn"\n',
        "no_main_scene": "",
    }.get(variant, 'run/main_scene="res://main.tscn"\n')
    features = '"4.7", "GL Compatibility"'
    if variant == "forward_plus_base":
        # The desktop renderer is a product decision: CI warns (PRJ005) but must still export and run this project,
        # because the Web platform forces Compatibility whatever the base key says.
        rendering = 'renderer/rendering_method="forward_plus"\n'
        features = '"4.7", "Forward Plus"'
    elif variant == "web_renderer_override":
        rendering = 'renderer/rendering_method="gl_compatibility"\nrenderer/rendering_method.web="forward_plus"\n'
    else:
        rendering = 'renderer/rendering_method="gl_compatibility"\n'
    return (
        "; Engine configuration file. GENERATED by the pipeline self-test. NOT THE GAME.\n"
        "config_version=5\n\n"
        "[application]\n\n"
        f'config/name="{SELFTEST_PROJECT_NAME}"\n'
        + main_scene
        + f"config/features=PackedStringArray({features})\n"
        + 'config/icon="res://icon.svg"\n\n'
        + "[rendering]\n\n"
        + rendering
    )


